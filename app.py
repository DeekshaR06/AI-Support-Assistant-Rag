"""
Streamlit demo UI for the Support Assistant. Run:  streamlit run app.py
(run `python train.py` first if you haven't - it needs the trained model + index)

Normal view = simple customer-facing page.
Developer view (sidebar switch) = technical details + evaluation results.
"""
import json
from pathlib import Path

import pandas as pd
import streamlit as st

from src.pipeline import SupportAssistant

ROOT = Path(__file__).parent
RESULTS_DIR = ROOT / "eval" / "results"

REASON_LABELS = {
    "empty_query": "No question entered",
    "customer_specific": "Needs account / order records",
    "no_evidence": "Not in the knowledge base",
    "low_coverage": "Knowledge base does not cover the details",
}

STAGES = [
    ("Baseline (original system)", "baseline41_all.json"),
    ("Step 2: + account-record and no-evidence rules", "step2_all.json"),
    ("Step 3: + term-coverage rule", "step3_all.json"),
]

st.set_page_config(page_title="AI Support Assistant", page_icon="\U0001F4AC", layout="centered")


@st.cache_resource
def get_assistant():
    return SupportAssistant()


def _frac(k, n):
    return f"{k}/{n} ({k / n:.0%})" if n else "n/a"


def stage_metrics(rows):
    ans = [r for r in rows if r["answerable"]]
    un = [r for r in rows if not r["answerable"]]
    ranks = [r["rank_of_first_relevant"] for r in ans]
    n = len(ans)
    mrr = sum(1 / (x + 1) for x in ranks if x is not None) / n if n else 0
    return {
        "Questions (answerable / unanswerable)": f"{len(ans)} / {len(un)}",
        "Correctly abstained (unanswerable)": _frac(sum(r["abstained"] for r in un), len(un)),
        "Answered anyway (unsafe)": _frac(sum(not r["abstained"] for r in un), len(un)),
        "Referred to support (answerable)": _frac(sum(r["abstained"] for r in ans), n),
        "Retrieval recall@1": f"{sum(x == 0 for x in ranks) / n:.2f}" if n else "n/a",
        "Retrieval recall@3": f"{sum(x is not None for x in ranks) / n:.2f}" if n else "n/a",
        "Retrieval MRR": f"{mrr:.2f}" if n else "n/a",
    }


def load_rows(filename):
    path = RESULTS_DIR / filename
    if not path.exists():
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)["rows"]


def render_assistant(assistant, dev):
    query = st.text_area(
        "How can we help?", placeholder="Type your question here...", height=100
    )

    if not st.button("Get answer", type="primary"):
        return
    if not query.strip():
        st.warning("Please type a question first.")
        return

    with st.spinner("Looking that up..."):
        result = assistant.handle(query)

    retrieved = result["retrieved"]

    # ---- developer-only: intent and sentiment ----
    if dev:
        col1, col2 = st.columns(2)
        with col1:
            st.metric("Detected intent", result["intent"]["intent"])
            st.caption(
                f"Intent classifier score: {result['intent']['confidence']:.0%} "
                "(uncalibrated; not used to choose the answer)"
            )
        with col2:
            st.metric("Detected sentiment", result["sentiment"]["label"])
            st.caption(f"VADER compound score: {result['sentiment']['compound']:+.2f}")

    # ---- the part every user sees ----
    if result["abstained"]:
        st.subheader("We couldn't answer this one")
        st.warning(result["answer"])
        if dev:
            label = REASON_LABELS.get(result["abstain_reason"], result["abstain_reason"])
            st.markdown(f"**Reason (dev):** {label}")
            st.caption("Nothing has been sent to a human. The customer should be referred to support.")
        evidence_title = "Closest articles found (NOT used for an answer)"
    else:
        st.subheader("Answer")
        st.info(result["answer"])
        if retrieved:
            top = retrieved[0]
            if dev:
                st.markdown(
                    f"**Source:** `{top['id']}` - {top['question']} (category: {top['category']})"
                )
                st.caption(f"Generated by: {result['generation_backend']}.")
            else:
                st.caption(f"Based on our FAQ: \"{top['question']}\"")
        evidence_title = "Retrieved evidence"

    # ---- developer-only: evidence and scores ----
    if dev:
        with st.expander(evidence_title):
            st.caption(
                "Similarity measures how related the text is, not whether the article "
                "answers the question or is correct."
            )
            for r in retrieved:
                st.markdown(
                    f"**{r['question']}**  \n`{r['id']}` | similarity: {r['similarity']}  \n{r['answer']}"
                )
        with st.expander("Intent classifier score breakdown"):
            st.json(result["intent"]["all_scores"])


def render_evaluation():
    st.subheader("Evaluation results")
    st.write(
        "The same 41 labeled questions were run through each version of the system. "
        "Saved results are read from `eval/results/`."
    )
    split = st.radio("Questions to include", ["all", "heldout", "dev"], horizontal=True)

    table = {}
    for name, fname in STAGES:
        rows = load_rows(fname)
        if rows is None:
            st.info(f"Missing result file: {fname}")
            continue
        subset = rows if split == "all" else [r for r in rows if r["split"] == split]
        table[name] = stage_metrics(subset)

    if table:
        st.dataframe(pd.DataFrame(table), use_container_width=True)

    st.markdown(
        "**How to read this**\n"
        "- *dev* questions were used while designing the rules, so those numbers are partly built in. "
        "*heldout* is the fairer view, and 10 of its questions were written by the project author.\n"
        "- The sets are tiny (22 answerable, 19 unanswerable). One question moves a rate by 4-5 points, "
        "so treat these as indicative, not statistically strong.\n"
        "- 'Referred to support (answerable)' counts answerable questions the system declined. "
        "Retrieval was not changed in these steps, so the retrieval rows stay the same.\n"
        "- The knowledge base is synthetic demo data."
    )


# ------------------------------------------------------------------ page ----
try:
    assistant = get_assistant()
except FileNotFoundError:
    st.error("Model files not found. Run `python train.py` from the project root first, then reload this page.")
    st.stop()

with st.sidebar:
    st.header("About")
    st.write("Ask a support question and get an answer from our help articles.")
    st.write("**Try:**")
    st.code("How long does shipping usually take?")
    st.code("Do you offer a student discount?")
    st.code("The app crashes every time I open it")
    st.divider()
    dev = st.checkbox("Developer view", value=False,
                      help="Shows technical details and evaluation results (for demos and review).")
    if dev:
        st.caption(
            "Default generation mode is offline template mode. Setting an `OPENAI_API_KEY` "
            "environment variable would switch it to an external LLM."
        )

st.title("AI Customer Support Assistant")
if dev:
    st.caption(
        "RAG pipeline: intent classification (TF-IDF + Logistic Regression) -> "
        "sentiment scoring (VADER) -> knowledge-base retrieval (LSA + FAISS) -> "
        "answerability check -> answer generation."
    )
st.caption("Demo: answers come from 22 example FAQ articles, not a real company's policies.")

if dev:
    tab_chat, tab_eval = st.tabs(["Assistant", "Evaluation"])
    with tab_chat:
        render_assistant(assistant, dev=True)
    with tab_eval:
        render_evaluation()
else:
    render_assistant(assistant, dev=False)